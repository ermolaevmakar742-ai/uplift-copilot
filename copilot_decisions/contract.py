"""ProductionDecision: immutable record of what production COPILOT ACTUALLY did
for one inbound message. The recorder never decides anything.

Field kinds
  identity     who/what the record is about
  action       a production choice that was made            (regime, model, ...)
  observation  a fact production saw when it chose          (trigger, state, ...)
  meta         provenance of the record itself
Unknown values are NULL and listed in metadata["unavailable"] with a reason.
"""
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

CONTRACT_VERSION = "production-decision-1"
SNAPSHOT_VERSION = "cs-snapshot-1"
DECISION_ID_PREFIX = "pd_"


class _Unknown:
    """Sentinel: 'the caller could not obtain this value' (distinct from None = known empty)."""
    _inst = None

    def __new__(cls):
        if cls._inst is None:
            cls._inst = super().__new__(cls)
        return cls._inst

    def __repr__(self):
        return "UNKNOWN"

    def __bool__(self):
        return False


UNKNOWN = _Unknown()

# name -> kind, source (where production gets it), meaning, nullable
FIELD_SPEC: dict[str, dict[str, Any]] = {
    "decision_id": dict(kind="identity", nullable=False, source="generated by recorder (uuid4)",
                        meaning="id of this one production decision; reused by shadow_decisions.decision_id"),
    "chat_id": dict(kind="identity", nullable=False, source="on_message: chat_id (Telegram user id)",
                    meaning="conversation / client"),
    "message_id": dict(kind="identity", nullable=True, source="on_message: event.message.id",
                       meaning="inbound Telegram message this decision answers"),
    "created_at": dict(kind="identity", nullable=False, source="recorder clock at decision time (UTC)",
                       meaning="when production decided (not DB insert time)"),
    "decision_path": dict(kind="action", nullable=False, source="constant per integration point",
                          meaning="which production path produced the action; only 'llm_reply' is recorded in phase 1"),
    "regime": dict(kind="action", nullable=True, source="on_message: regime (after select_ai_route + objection override)",
                   meaning="final conversation regime used for the reply"),
    "model": dict(kind="action", nullable=True, source="generate_ai_reply: used_model",
                  meaning="model that actually produced the reply (intended model in metadata)"),
    "flow_version": dict(kind="action", nullable=True, source="on_message: flow_version (v37 default / experiment variant)",
                         meaning="prompt flow version applied"),
    "used_fallback": dict(kind="action", nullable=True, source="generate_ai_reply: used_fallback",
                          meaning="primary model failed and fallback produced the reply"),
    "reply_parts": dict(kind="action", nullable=True, source="_split_reply_into_parts(reply) after send_humanized normalisation",
                        meaning="PLANNED number of Telegram messages (actual per-part send failures are not observed)"),
    "trigger": dict(kind="observation", nullable=True, source="on_message: detect_trigger(text)",
                    meaning="non-fixed trigger detected in the client's text; NULL = none or unknown (see metadata)"),
    "experiment_id": dict(kind="observation", nullable=True, source="NOT exposed by get_experiment_variant",
                          meaning="Experiment row id; always NULL in phase 1 (experiment name in metadata)"),
    "experiment_variant": dict(kind="observation", nullable=True, source="get_experiment_variant -> assigned_version",
                               meaning="variant assigned by the experiment; NULL = no assignment or unknown"),
    "objection_signal": dict(kind="observation", nullable=True, source="on_message: detect_objection_regime(text) (text_regime)",
                             meaning="regime suggested by objection/action text markers ('' -> NULL)"),
    "language_mode": dict(kind="observation", nullable=True, source="language_layer.get_config()",
                          meaning="language layer state at decision time: off | shadow | active"),
    "client_state_snapshot": dict(kind="observation", nullable=True, source="build_client_state() dict, whitelisted",
                                  meaning="minimal non-PII state at decision time"),
    "metadata": dict(kind="meta", nullable=False, source="recorder",
                     meaning="contract version, unavailable-field reasons, intended model, provenance"),
}

# Whitelist of Client State paths copied into the snapshot. Nothing else is ever stored:
# not last_message / history / identity name / username / memory raw / risk flags.
SNAPSHOT_WHITELIST = (
    ("stage",), ("conversation", "intent"), ("conversation", "sentiment"),
    ("conversation", "complexity"), ("conversation", "messages_count"), ("identity", "region"),
)
SNAPSHOT_NOT_CAPTURED = {
    "risk": "client_state.risk flags are always False today (User has no such columns): not a real signal",
    "language": "client_state has no language field",
    "readiness": "client_state has no readiness field",
}


def build_client_state_snapshot(client_state) -> dict | None:
    if not isinstance(client_state, dict):
        return None
    snap: dict[str, Any] = {}
    for path in SNAPSHOT_WHITELIST:
        cur: Any = client_state
        for k in path:
            cur = cur.get(k) if isinstance(cur, dict) else None
        if isinstance(cur, (str, int, float, bool)) or cur is None:
            if path[-1] == "region" and not (isinstance(cur, str) and 2 <= len(cur) <= 3 and cur != "??"):
                cur = None
            snap["_".join(path[-1:])] = cur
    snap["snapshot_version"] = SNAPSHOT_VERSION
    return snap


@dataclass(frozen=True)
class ProductionDecision:
    decision_id: str
    chat_id: int
    message_id: int | None
    created_at: datetime
    decision_path: str = "llm_reply"
    regime: str | None = None
    model: str | None = None
    flow_version: str | None = None
    used_fallback: bool | None = None
    reply_parts: int | None = None
    trigger: str | None = None
    experiment_id: int | None = None
    experiment_variant: str | None = None
    objection_signal: str | None = None
    language_mode: str | None = None
    client_state_snapshot: dict | None = None
    metadata: dict = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not (isinstance(self.decision_id, str) and self.decision_id.startswith(DECISION_ID_PREFIX)
                and len(self.decision_id) > len(DECISION_ID_PREFIX)):
            raise ValueError("decision_id must be a non-empty 'pd_...' string")
        if isinstance(self.chat_id, bool) or not isinstance(self.chat_id, int):
            raise TypeError("chat_id must be int")
        if self.message_id is not None and (isinstance(self.message_id, bool) or not isinstance(self.message_id, int)):
            raise TypeError("message_id must be int or None")
        if not isinstance(self.created_at, datetime) or self.created_at.tzinfo is None:
            raise ValueError("created_at must be a timezone-aware datetime")
        if self.reply_parts is not None and (not isinstance(self.reply_parts, int) or self.reply_parts < 0):
            raise ValueError("reply_parts must be a non-negative int or None")
        if self.used_fallback is not None and not isinstance(self.used_fallback, bool):
            raise TypeError("used_fallback must be bool or None")
        for name in ("regime", "model", "flow_version", "trigger", "experiment_variant",
                     "objection_signal", "language_mode", "decision_path"):
            v = getattr(self, name)
            if v is not None and not isinstance(v, str):
                raise TypeError(f"{name} must be str or None")
        if not isinstance(self.metadata, dict):
            raise TypeError("metadata must be a dict")

    def to_row(self) -> dict:
        """Plain dict for INSERT (deep-copied so later mutation of the source cannot alter history)."""
        import copy
        return {k: copy.deepcopy(getattr(self, k)) for k in FIELD_SPEC}

    def to_dict(self) -> dict:
        d = self.to_row()
        d["created_at"] = self.created_at.isoformat()
        return d
